#!/usr/bin/env python3
"""Builds supabase/seed-ydl.sql: Shaan Fitness's own membership plans and batches, exactly as
they are in YDL (docs/ydl/config/*.json, read from YDL on 8 Oct 2026). Codes keep YDL's
numbers (plan YD-76898, Batch-5755) so old bills and receipts can be matched on import.
Run: python3 scripts/build-seed-ydl.py"""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
plans = json.loads((root / 'docs/ydl/config/plans.json').read_text())
batches = json.loads((root / 'docs/ydl/config/batches.json').read_text())
STUDIO = "'00000000-0000-4000-8000-000000000001'"
DAYS = {'Monday': 1, 'Tuesday': 2, 'Wednesday': 3, 'Thursday': 4, 'Friday': 5, 'Saturday': 6, 'Sunday': 7}
APPT = {'Daily': 'daily', 'Alternate Day': 'alternate_day', 'Every Third Day': 'every_third_day', 'Once A Week': 'once_a_week', 'One Time': 'one_time'}


def q(s):
    return 'null' if s is None or s == '' else "'" + str(s).replace("'", "''") + "'"


def services(names):
    arr = ','.join(q(n) for n in names)
    return f"array(select s.id from public.services s where s.studio_id = {STUDIO} and s.name = any (array[{arr}]::text[]) order by s.sort)" if names else "'{}'::uuid[]"


def clock(t):
    m = re.match(r'(\d{1,2}):(\d{2})\s*([ap])\.m\.', t.strip())
    h, mi, ap = int(m.group(1)), int(m.group(2)), m.group(3)
    if ap == 'p' and h < 12:
        h += 12
    if ap == 'a' and h == 12:
        h = 0
    return f'{h:02d}:{mi:02d}'


out = ['-- Shaan Fitness membership plans and batches, as set up in YDL (generated by scripts/build-seed-ydl.py).',
       '-- Runs once on a new database; edit plans and batches in the app afterwards.', '']
out.append('insert into public.plans (studio_id, plan_code, name, description, kind, service_ids, show_in_app, terms, session_count,')
out.append('  unlimited_sessions, disable_messages_followups, tenure_value, tenure_unit, is_one_time, freeze_days, weekly_class_limit,')
out.append('  is_free_trial, price, discount_price, app_sequence, appointment_type, faqs, guidelines, dos_donts, shopping_list, snack_list,')
out.append('  activities, other_text, active)')
out.append('select v.* from (values')
rows = []
for p in plans:
    kind = 'pt' if p['sessions'] > 0 else 'gym'
    rows.append('  (' + ', '.join([
        STUDIO + '::uuid', q('YD-' + p['ydl_id']), q(p['name']), q(p['description']), q(kind), services(p['services']),
        'true' if p['show_in_app'] else 'false', q(p['terms']), str(p['sessions']) if p['sessions'] > 0 else 'null::int',
        'true' if p['unlimited'] else 'false', 'true' if p['no_msg'] else 'false', str(p['tenure']), q(p['unit']),
        'true' if p['one_time'] else 'false', str(p['freeze']), str(p['class_limit']), 'true' if p['trial'] else 'false',
        f"{p['price']:.2f}", f"{p['discount']:.2f}" if p['discount'] is not None else 'null::numeric', str(p['seq']),
        q(APPT.get(p['appointment'] or '')), q(p['faqs']), q(p['guidelines']), q(p['dos']), q(p['shopping']), q(p['snacks']),
        q(p['activities']), q(p['other']), 'true' if p['active'] else 'false',
    ]) + ')')
out.append(',\n'.join(rows))
out.append(') as v')
out.append(f'where not exists (select 1 from public.plans x where x.studio_id = {STUDIO});')
out.append('')

out.append('insert into public.batches (studio_id, batch_code, name, info, capacity, room, service_ids, start_date, end_date, days, start_time, end_time, gender)')
out.append('select v.* from (values')
rows = []
for b in sorted(batches, key=lambda b: clock(b['slots'][0][0])):
    start, end, gender = b['slots'][0]
    days = '{' + ','.join(str(DAYS[d]) for d in b['days']) + '}'
    rows.append('  (' + ', '.join([
        STUDIO + '::uuid', q('Batch-' + b['ydl_id']), q(b['name']), q(b['info']), str(b['capacity']) if b['capacity'] else 'null::int', q(b['room']),
        services(b['services']), q(b['start_date']) + '::date', q(b['end_date']) + '::date', f"'{days}'::smallint[]",
        f"'{clock(start)}'::time", f"'{clock(end)}'::time", q('all' if gender == 'unisex' else gender),
    ]) + ')')
out.append(',\n'.join(rows))
out.append(') as v')
out.append(f'where not exists (select 1 from public.batches x where x.studio_id = {STUDIO});')
(root / 'supabase/seed-ydl.sql').write_text('\n'.join(out) + '\n')
print(f'wrote supabase/seed-ydl.sql: {len(plans)} plans ({sum(p["active"] for p in plans)} active), {len(batches)} batches')
