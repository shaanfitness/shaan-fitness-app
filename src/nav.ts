export const pageFor = (path: string) => ALL_PAGES.find((p) => p.path === path)
export const navFor = (role: Role) =>
  NAV.map((g) => ({ ...g, pages: g.pages.filter((p) => p.roles.includes(role)) })).filter((g) => g.pages.length > 0)
